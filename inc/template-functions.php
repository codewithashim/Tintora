/**
 * Adds custom classes to the array of body classes.
 *
 * @param array $classes Classes for the body element.
 * @return array Modified body classes.
 */
function tintora_body_classes( $classes ) {
	// Adds a class of hfeed to non-singular pages.
	if ( ! is_singular() ) {
		$classes[] = 'hfeed';
	}

	// Sticky header status
	if ( get_theme_mod( 'tintora_sticky_header', true ) ) {
		$classes[] = 'has-sticky-header';
	}

	// Action bar status
	if ( get_theme_mod( 'tintora_enable_mobile_action_bar', true ) ) {
		$classes[] = 'has-mobile-action-bar';
	}

	// Homepage transparent header
	if ( is_front_page() && get_theme_mod( 'tintora_transparent_header', true ) ) {
		$classes[] = 'has-transparent-hero-header';
	}

	return $classes;
}
add_filter( 'body_class', 'tintora_body_classes' );

/**
 * Add a pingback url auto-discovery header for single posts, pages, or attachments.
 */
function tintora_pingback_header() {
	if ( is_singular() && pings_open() ) {
		printf( '<link rel="pingback" href="%s">', esc_url( get_bloginfo( 'pingback_url' ) ) );
	}
}
add_action( 'wp_head', 'tintora_pingback_header' );

/**
 * Calculate Estimated Reading Time
 *
 * @param int $post_id Post ID.
 * @return string Reading time string (e.g., "3 min read").
 */
function tintora_estimated_reading_time( $post_id = null ) {
	if ( ! $post_id ) {
		$post_id = get_the_ID();
	}
	$content    = get_post_field( 'post_content', $post_id );
	$word_count = str_word_count( wp_strip_all_tags( $content ) );
	$minutes    = max( 1, ceil( $word_count / 200 ) );

	/* translators: %d: estimated minutes */
	return sprintf( esc_html__( '%d min read', 'tintora' ), $minutes );
}

